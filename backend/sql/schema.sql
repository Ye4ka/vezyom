-- Схема БД «Везём» (PostgreSQL). Соответствует моделям Django из menu/models.py

CREATE TABLE menu_restaurant (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    address       VARCHAR(200) NOT NULL DEFAULT '',
    rating        NUMERIC(2,1) NOT NULL DEFAULT 0,
    delivery_time SMALLINT     NOT NULL DEFAULT 30 CHECK (delivery_time >= 0)
);

CREATE TABLE menu_category (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE menu_dish (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT         NOT NULL REFERENCES menu_restaurant (id) ON DELETE CASCADE,
    category_id   BIGINT         NOT NULL REFERENCES menu_category (id)   ON DELETE RESTRICT,
    name          VARCHAR(100)   NOT NULL,
    description   TEXT           NOT NULL DEFAULT '',
    price         NUMERIC(8,2)   NOT NULL CHECK (price >= 0),
    weight        INTEGER        CHECK (weight >= 0),
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX menu_dish_restaurant_idx ON menu_dish (restaurant_id);
CREATE INDEX menu_dish_category_idx   ON menu_dish (category_id);