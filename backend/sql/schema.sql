-- Схема БД «Везём» (PostgreSQL). Соответствует моделям Django из menu/models.py

CREATE TABLE menu_restaurant (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    address       VARCHAR(200) NOT NULL DEFAULT '',
    rating        NUMERIC(2,1) NOT NULL DEFAULT 0,
    delivery_time SMALLINT     NOT NULL DEFAULT 30 CHECK (delivery_time >= 0)
);

CREATE TABLE menu_category (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE menu_dish (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT         NOT NULL REFERENCES menu_restaurant (id) ON DELETE CASCADE,
    category_id   BIGINT         NOT NULL REFERENCES menu_category (id)   ON DELETE RESTRICT,
    name          VARCHAR(100)   NOT NULL,
    description   TEXT           NOT NULL DEFAULT '',
    price         NUMERIC(8,2)   NOT NULL CHECK (price >= 0),
    weight        INTEGER        CHECK (weight >= 0),
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX menu_dish_restaurant_idx ON menu_dish (restaurant_id);
CREATE INDEX menu_dish_category_idx   ON menu_dish (category_id);


CREATE TABLE auth_user (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password     VARCHAR(128) NOT NULL,
    last_login   TIMESTAMPTZ,
    is_superuser BOOLEAN      NOT NULL,
    username     VARCHAR(150) NOT NULL UNIQUE,
    first_name   VARCHAR(150) NOT NULL,
    last_name    VARCHAR(150) NOT NULL,
    email        VARCHAR(254) NOT NULL,
    is_staff     BOOLEAN      NOT NULL,
    is_active    BOOLEAN      NOT NULL,
    date_joined  TIMESTAMPTZ  NOT NULL
);

-- Профиль: ФИО и роль (USER / ADMIN), связь 1:1 с пользователем
CREATE TABLE accounts_profile (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   INTEGER      NOT NULL UNIQUE REFERENCES auth_user (id) ON DELETE CASCADE,
    full_name VARCHAR(150) NOT NULL,
    role      VARCHAR(10)  NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN'))
);

-- Заказ принадлежит пользователю (FK user_id), связь 1:N
CREATE TABLE orders_order (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INTEGER      NOT NULL REFERENCES auth_user (id)       ON DELETE CASCADE,
    restaurant_id BIGINT       NOT NULL REFERENCES menu_restaurant (id) ON DELETE RESTRICT,
    address       VARCHAR(200) NOT NULL,
    comment       TEXT         NOT NULL DEFAULT '',
    status        VARCHAR(15)  NOT NULL DEFAULT 'NEW'
                  CHECK (status IN ('NEW', 'IN_PROGRESS', 'DONE', 'CANCELED')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Позиции заказа: заказ 1:N позиции, блюдо 1:N позиции
CREATE TABLE orders_orderitem (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT       NOT NULL REFERENCES orders_order (id) ON DELETE CASCADE,
    dish_id  BIGINT       NOT NULL REFERENCES menu_dish (id)    ON DELETE RESTRICT,
    quantity SMALLINT     NOT NULL CHECK (quantity >= 0),
    price    NUMERIC(8,2) NOT NULL
);

CREATE INDEX orders_order_user_idx      ON orders_order (user_id);
CREATE INDEX orders_orderitem_order_idx ON orders_orderitem (order_id);